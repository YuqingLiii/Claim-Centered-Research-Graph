def selftest(args):
    if len(args)!=2: die('selftest OUTDIR SPECDIR')
    out=Path(args[0]); spec=Path(args[1]); man=json.load(open(out/'canonical_K_pencil_manifest.json'))
    if man.get('status')!='CANONICAL_20_K_PENCILS_CONSTRUCTED': die('manifest status')
    if len(man['blocks'])!=20: die('block count')
    for b in man['blocks']:
        z=np.load(out/b['cache_file'])
        for arr,key in [('V_modp','V_modp_sha256'),('C_modp','C_modp_sha256'),('Z_modp','Z_modp_sha256')]:
            if hash_u16(z[arr])!=b[key]: die('%s hash mismatch block %s'%(arr,b['gap_irrep_id']))
        C=z['C_modp'].astype(np.int64); Z=z['Z_modp'].astype(np.int64)
        if np.any((C@Z)%P): die('C Z failure block %s'%b['gap_irrep_id'])
        if det_mod(C[np.ix_(z['pivot_rows'],z['pivot_columns'])])!=int(b['pivot_minor_det_mod_24001']):die('minor mismatch')
    print(json.dumps({'status':'SELFTEST_PASSED','blocks':20,'manifest_sha256':sha(out/'canonical_K_pencil_manifest.json')},indent=2,sort_keys=True))


