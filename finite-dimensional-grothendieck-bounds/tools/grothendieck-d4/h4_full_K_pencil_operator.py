def coeff_kron_i64(A,B):
    A=np.asarray(A,dtype=np.int64); B=np.asarray(B,dtype=np.int64)
    aa=A[:,:,None,None,0]; ab=A[:,:,None,None,1]; ac=A[:,:,None,None,2]; ad=A[:,:,None,None,3]
    ba=B[None,None,:,:,0]; bb=B[None,None,:,:,1]; bc=B[None,None,:,:,2]; bd=B[None,None,:,:,3]
    O=np.empty((A.shape[0],A.shape[1],B.shape[0],B.shape[1],4),dtype=np.int64)
    O[...,0]=aa*ba+5*ab*bb-ac*bc-5*ad*bd
    O[...,1]=aa*bb+ab*ba-ac*bd-ad*bc
    O[...,2]=aa*bc+5*ab*bd+ac*ba+5*ad*bb
    O[...,3]=aa*bd+ab*bc+ac*bb+ad*ba
    return O.transpose(0,2,1,3,4).reshape(A.shape[0]*B.shape[0],A.shape[1]*B.shape[1],4)


def fast_h_elem_i64(meta,Q64,G,gi):
    pid,e=G['elements'][int(gi)]; a,b=G['pairs'][pid]
    if meta['type']=='diagonal_extension':
        U,D,met=Q64[int(meta['i'])]
        M=coeff_kron_i64(U[a],U[b]); du=U.shape[1]
        if e:
            src=np.empty(du*du,dtype=np.int32)
            for i in range(du):
                for j in range(du): src[i*du+j]=j*du+i
            M=M[:,src,:]
            if int(meta['extension_sign'])==-1: M=-M
        return M,int(D*D),[int(x)*int(y) for x in met for y in met]
    U,DU,mU=Q64[int(meta['i'])]; V,DV,mV=Q64[int(meta['j'])]
    du=U.shape[1]; dv=V.shape[1]; r=du*dv
    A=coeff_kron_i64(U[a],V[b]); B=coeff_kron_i64(V[a],U[b])
    M=np.zeros((2*r,2*r,4),dtype=np.int64); M[:r,:r,:]=A; M[r:,r:,:]=B
    if e:
        F=np.empty(r,dtype=np.int32)
        for i in range(du):
            for j in range(dv): F[i*dv+j]=j*du+i
        inv=np.empty(r,dtype=np.int32)
        for src,dst in enumerate(F): inv[int(dst)]=src
        src=np.empty(2*r,dtype=np.int32)
        for c in range(r): src[c]=r+F[c]; src[r+c]=inv[c]
        M=M[:,src,:]
    return M,int(DU*DV),[int(x)*int(y) for x in mU for y in mV]+[int(x)*int(y) for x in mV for y in mU]

def exact_V_numerator_fast(meta,Q64,G,inv_idx,inds,chars,pivot_cols):
    acc=None; den0=None; metric0=None
    for h,ch in zip(inds,chars):
        M,D,met=fast_h_elem_i64(meta,Q64,G,int(inv_idx[int(h)]))
        A=M[:,pivot_cols,:]
        if acc is None:
            acc=np.zeros_like(A,dtype=np.int64); den0=D; metric0=met
        if D!=den0 or met!=metric0: die('representation denominator/metric varied')
        acc += int(ch)*A
    return acc,int(den0),metric0

