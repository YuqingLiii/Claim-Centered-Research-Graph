def q_bilinear_J(Qdata, qi):
    r=Qdata['irreps'][int(qi)]; d=int(r['degree']); par=int(r['center_parity'])
    if d==4 and par==1:
        J1=np.array([[0,1],[-1,0]],dtype=np.int64)
        return np.kron(J1,J1)
    n=d-1
    J=np.zeros((d,d),dtype=np.int64)
    for k in range(d): J[k,n-k]=((-1)**k)*math.comb(n,k)
    return J


def structural_bilinear_J(meta,Qdata,genmats):
    if meta['type']=='diagonal_extension':
        JU=q_bilinear_J(Qdata,int(meta['i']))
        J=np.kron(JU,JU)
    else:
        JU=q_bilinear_J(Qdata,int(meta['i'])); JV=q_bilinear_J(Qdata,int(meta['j']))
        J1=np.kron(JU,JV); J2=np.kron(JV,JU)
        J=np.zeros((J1.shape[0]+J2.shape[0],J1.shape[1]+J2.shape[1]),dtype=np.int64)
        J[:J1.shape[0],:J1.shape[1]]=J1; J[J1.shape[0]:,J1.shape[1]:]=J2
    J%=P
    if not np.array_equal(J,J.T): die('H4 bilinear J must be symmetric')
    if det_mod(J)==0: die('structural bilinear J singular')
    for Gm in genmats:
        if not np.array_equal((Gm.T@J@Gm)%P,J): die('structural bilinear J invariance failed')
    return J

def sparse_block_symmetry_test(theta, ids, sgn, pairidx, active, Vcat, J, Rhat):
    """Build an exact GF(p) B for a deterministic sparse theta and test B=B^T.

    This is only an indexing/convention self-test, not a PSD test.
    """
    m=Vcat.shape[1]; d=Vcat.shape[0]
    B=np.zeros((m,m),dtype=np.int64)
    RF=Rhat.reshape(ORDER,d*d)
    # theta is dict global moment id -> residue
    for ai,Oi in enumerate(active):
        si=slice(Oi['copy_start'],Oi['copy_end']); Vi=Vcat[:,si]
        for aj in range(ai,len(active)):
            Oj=active[aj]; sj=slice(Oj['copy_start'],Oj['copy_end']); Vj=Vcat[:,sj]
            key=tuple(sorted((Oi['nonD_index'],Oj['nonD_index'])))
            pr=pairidx[key]; mids=np.asarray(ids[pr]); ss=np.asarray(sgn[pr],dtype=np.int64)
            ell=np.zeros(ORDER,dtype=np.int64)
            for mid,val in theta.items():
                q=np.flatnonzero(mids==int(mid))
                if len(q): ell[q]=ss[q]*int(val)
            if np.any(ell):
                # signed ell * residues: int64 absolute bound < 14400*p^2
                F=(ell@RF)%P; F=F.reshape(d,d)
                T=(Vi.T@J)%P
                T=(T@F)%P
                M=(T@Vj)%P
                B[si,sj]=M
                if aj!=ai: B[sj,si]=M.T
    if not np.array_equal(B,B.T): die("sparse block construction lost symmetry")
    return hashlib.sha256(B.astype('<u2').tobytes()).hexdigest()


