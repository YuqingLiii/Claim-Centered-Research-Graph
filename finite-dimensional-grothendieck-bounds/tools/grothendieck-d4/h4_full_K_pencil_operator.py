def Asha(A):
    h=hashlib.sha256()
    for x in A.ravel(order="C"):
        h.update(int(x).to_bytes(8,"little",signed=True))
    return h.hexdigest()


def exact_int_matrix(raw):
    a=np.asarray(raw); out=np.empty(a.shape,dtype=np.int64)
    it=np.nditer(a,flags=["multi_index"])
    for z in it:
        x=float(z); q=int(x)
        if float(q)!=x: die("A is not exactly integral")
        out[it.multi_index]=q
    return out


def exact_sign_vector(raw):
    a=np.asarray(raw).reshape(-1); out=np.empty(len(a),dtype=np.int8)
    for i,z in enumerate(a):
        x=float(z)
        if x not in (-1.0,1.0): die("non-sign vector")
        out[i]=int(x)
    return out


