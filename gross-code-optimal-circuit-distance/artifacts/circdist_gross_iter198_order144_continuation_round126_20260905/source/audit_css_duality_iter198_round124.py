#!/usr/bin/env python3
"""Independent exact CSS-duality audit for the iteration-198 Gross registry.

This script uses only the Python standard library.  It checks the concrete qubit,
check, edge, overlap, stabilizer, detector, and logical-quotient action; proves the
presentation generated by translations and the CSS involution on all named edges;
and inventories exact block/selector images and missing translation orbits.
"""
from __future__ import annotations

import argparse
import collections
import gzip
import hashlib
import json
from pathlib import Path

L, M, G, N = 12, 6, 72, 144
DELTAS = tuple((i, j) for i in range(L) for j in range(M))
GENERATORS = ((1, 0), (0, 1))


def canonical_sha(obj):
    return hashlib.sha256(json.dumps(obj, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def file_sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(8 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def add(g, delta):
    i, j = divmod(int(g), M)
    return ((i + delta[0]) % L) * M + ((j + delta[1]) % M)


def neg(g):
    i, j = divmod(int(g), M)
    return ((-i) % L) * M + ((-j) % M)


def tq(q, delta):
    q = int(q)
    return add(q, delta) if q < G else G + add(q - G, delta)


def dq(q):
    q = int(q)
    return G + neg(q) if q < G else neg(q - G)


def te(edge, delta):
    kind, check, qubit = edge.split(":")
    return f"{kind}:{add(check, delta)}:{tq(qubit, delta)}"


def de(edge):
    kind, check, qubit = edge.split(":")
    assert kind in ("X", "Z")
    return f"{'Z' if kind == 'X' else 'X'}:{neg(check)}:{dq(qubit)}"


def tmask(value, delta):
    value, out = int(value), 0
    while value:
        bit = value & -value
        q = bit.bit_length() - 1
        out |= 1 << tq(q, delta)
        value ^= bit
    return out


def dmask(value):
    value, out = int(value), 0
    while value:
        bit = value & -value
        q = bit.bit_length() - 1
        out |= 1 << dq(q)
        value ^= bit
    return out


def mask(items):
    out = 0
    for item in items:
        out |= 1 << int(item)
    return out


def rref(rows, width=N):
    rows = [int(row) for row in rows if int(row)]
    pivot_row = 0
    for col in range(width - 1, -1, -1):
        pivot = next((i for i in range(pivot_row, len(rows)) if (rows[i] >> col) & 1), None)
        if pivot is None:
            continue
        rows[pivot_row], rows[pivot] = rows[pivot], rows[pivot_row]
        for i in range(len(rows)):
            if i != pivot_row and ((rows[i] >> col) & 1):
                rows[i] ^= rows[pivot_row]
        pivot_row += 1
        if pivot_row == len(rows):
            break
    return tuple(rows[:pivot_row])


def block_key(block):
    return tuple(sorted((str(a), str(b)) for a, b in block["atoms"]))


def tblock(key, delta):
    return tuple(sorted((te(a, delta), te(b, delta)) for a, b in key))


def dblock(key):
    return tuple(sorted((de(a), de(b)) for a, b in key))


def selector_key(selector):
    groups = tuple(sorted((int(c), tuple(sorted(map(int, kinds))))
                          for c, kinds in selector["group_kinds"].items()))
    return (str(selector["sector"]), tuple(sorted(map(int, selector["data_support"]))), groups)


def tselector(key, delta):
    sector, data, groups = key
    return (sector, tuple(sorted(tq(q, delta) for q in data)),
            tuple(sorted((add(c, delta), kinds) for c, kinds in groups)))


def dselector(key):
    sector, data, groups = key
    return ("Zerr" if sector == "Xerr" else "Xerr",
            tuple(sorted(dq(q) for q in data)),
            tuple(sorted((neg(c), kinds) for c, kinds in groups)))


def selector_semantics(key):
    sector, data, groups = key
    names = [f"D:{q}" for q in data]
    group_dict = {str(c): list(kinds) for c, kinds in groups}
    for c, kinds in groups:
        names.extend(f"R:{c}:{kind}" for kind in kinds)
    return {"sector": sector, "selected_names": names,
            "data_support": list(data), "group_kinds": group_dict}


def orbit_histogram(keys, transform):
    keyset = set(keys)
    remaining = set(keyset)
    hist = collections.Counter()
    while remaining:
        parent = next(iter(remaining))
        orbit = {transform(parent, delta) for delta in DELTAS}
        assert orbit <= keyset
        hist[len(orbit)] += 1
        remaining.difference_update(orbit)
    return dict(sorted((str(k), v) for k, v in hist.items()))


def parity(a, b):
    return bin(int(a) & int(b)).count("1") & 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, required=True)
    ap.add_argument("--state", type=Path, required=True)
    ap.add_argument("--candidate", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()

    with gzip.open(args.source, "rt") as f:
        source = json.load(f)
    state = json.loads(args.state.read_text())
    candidate = json.loads(args.candidate.read_text())
    claimed_semantic = source.pop("semantic_payload_sha256")
    observed_semantic = canonical_sha(source)
    source["semantic_payload_sha256"] = claimed_semantic
    assert claimed_semantic == observed_semantic
    assert file_sha(args.source) == state["source_file_sha256"]
    assert claimed_semantic == state["source_semantic_payload_sha256"]
    assert [len(source["blocks"]), len(source["selectors"])] == [814392, 51840]

    edges = tuple(map(str, source["edges"]))
    edge_set = set(edges)
    assert len(edges) == len(edge_set) == 864
    assert {de(edge) for edge in edges} == edge_set
    assert all(de(de(edge)) == edge for edge in edges)
    involution_edge_cases = len(edges)

    # Translation action and the dihedral presentation on every concrete edge.
    translation_composition_cases = 0
    for left in DELTAS:
        for right in DELTAS:
            total = ((left[0] + right[0]) % L, (left[1] + right[1]) % M)
            for edge in edges:
                assert te(te(edge, left), right) == te(edge, total)
                translation_composition_cases += 1
    conjugation_edge_cases = 0
    for delta in DELTAS:
        inverse = ((-delta[0]) % L, (-delta[1]) % M)
        for edge in edges:
            assert de(te(de(edge), delta)) == te(edge, inverse)
            conjugation_edge_cases += 1
    action_hashes = set()
    for epsilon in (0, 1):
        for delta in DELTAS:
            mapping = {edge: te(de(edge), delta) if epsilon else te(edge, delta) for edge in edges}
            assert set(mapping.values()) == edge_set
            action_hashes.add(canonical_sha(mapping))
    assert len(action_hashes) == 144

    # Concrete Gross incidence geometry and MC overlaps.
    xchecks = source["x_checks"]
    zchecks = source["z_checks"]
    geometry_check_cases = 0
    for c in range(G):
        assert sorted(dq(q) for q in xchecks[c]) == sorted(zchecks[neg(c)])
        assert sorted(dq(q) for q in zchecks[c]) == sorted(xchecks[neg(c)])
        geometry_check_cases += 2
    for q in range(N):
        assert sorted(de(edge) for edge in source["data_incidence"][q]) == \
               sorted(source["data_incidence"][dq(q)])
        geometry_check_cases += 1
    overlap_set = {(int(row["x_check"]), int(row["z_check"]), tuple(map(int, row["qubits"])))
                   for row in source["overlaps"]}
    mapped_overlaps = {(neg(z), neg(x), tuple(sorted(dq(q) for q in qs)))
                       for x, z, qs in overlap_set}
    assert mapped_overlaps == overlap_set and len(overlap_set) == 648

    # Sector semantics.  D swaps hook checks and detector checks, and maps the
    # stabilizer subspace exactly.  The combined detector+logical row kernel is
    # exactly the stabilizer space, so zero syndrome/nontrivial quotient is
    # preserved even though the retained logical bases need not map row-by-row.
    sector_rows = {}
    for label, check_rows, detector_check_rows in (
            ("Xerr", xchecks, zchecks), ("Zerr", zchecks, xchecks)):
        definition = source["sector_definitions"][label]
        assert definition["checks"] == check_rows
        detector = tuple(map(int, definition["detector_rows"]))
        logical = tuple(map(int, definition["logical_duals"]))
        stabilizer = tuple(mask(row) for row in check_rows)
        expected_detector = tuple(mask(row) for row in detector_check_rows)
        assert detector == expected_detector
        signatures = [sum(((row >> q) & 1) << i for i, row in enumerate(detector + logical))
                      for q in range(N)]
        assert signatures == list(map(int, definition["qubit_signatures"]))
        assert len(rref(stabilizer)) == len(rref(detector)) == 66
        assert len(rref(detector + logical)) == 78
        assert all(parity(s, row) == 0 for s in stabilizer for row in detector + logical)
        assert rref(stabilizer) == rref(rref(stabilizer))
        sector_rows[label] = {"stabilizer": stabilizer, "detector": detector,
                              "logical": logical, "combined": detector + logical}
    assert rref(map(dmask, sector_rows["Xerr"]["stabilizer"])) == rref(sector_rows["Zerr"]["stabilizer"])
    assert rref(map(dmask, sector_rows["Zerr"]["stabilizer"])) == rref(sector_rows["Xerr"]["stabilizer"])
    assert rref(map(dmask, sector_rows["Xerr"]["detector"])) == rref(sector_rows["Zerr"]["detector"])
    assert rref(map(dmask, sector_rows["Zerr"]["detector"])) == rref(sector_rows["Xerr"]["detector"])
    assert rref(map(dmask, sector_rows["Xerr"]["combined"])) == rref(sector_rows["Zerr"]["combined"])
    assert rref(map(dmask, sector_rows["Zerr"]["combined"])) == rref(sector_rows["Xerr"]["combined"])
    assert source["residual_positions"] == [[0, 1], [3, 4, 5], [4, 5]]

    # The concrete mandatory schedule is also transported, with order positions
    # and layer labels unchanged.  Check edge completeness, conflicts, MC, and
    # global interleaving directly for the original and dual schedules.
    times = {str(edge): int(t) for edge, t in candidate["compressed_times"].items()}
    assert set(times) == edge_set
    dual_times = {de(edge): t for edge, t in times.items()}
    assert set(dual_times) == edge_set and len(dual_times) == 864
    def schedule_facts(schedule):
        occupied = set()
        for edge, t in schedule.items():
            kind, c, q = edge.split(":")
            for resource in ((kind, int(c), t), ("D", int(q), t)):
                assert resource not in occupied
                occupied.add(resource)
        for x, z, qs in overlap_set:
            orientations = [schedule[f"Z:{z}:{q}"] < schedule[f"X:{x}:{q}"] for q in qs]
            assert len(set(orientations)) == 1
        xv = [t for edge, t in schedule.items() if edge.startswith("X:")]
        zv = [t for edge, t in schedule.items() if edge.startswith("Z:")]
        assert not (max(xv) < min(zv) or max(zv) < min(xv))
        return {"edge_count": len(schedule), "resource_occupancies": len(occupied),
                "mc_overlaps": len(overlap_set), "used_layers": len(set(schedule.values())),
                "global_interleaved": True, "schedule_sha256": canonical_sha(schedule)}
    schedule_original = schedule_facts(times)
    schedule_dual = schedule_facts(dual_times)
    assert sorted(times.values()) == sorted(dual_times.values())

    # Exact registry image inventory.  Identity is decided from full tuples; hashes
    # are labels only.  The missing image sets must themselves be translation closed.
    blocks = source["blocks"]
    block_keys = [block_key(block) for block in blocks]
    block_set = set(block_keys)
    assert len(block_keys) == len(block_set)
    block_duals = [dblock(key) for key in block_keys]
    assert len(set(block_duals)) == len(block_duals)
    assert all(dblock(dkey) == key for key, dkey in zip(block_keys, block_duals))
    block_missing = set(block_duals) - block_set
    block_intersection = len(block_set) - len(block_missing)
    assert all(tblock(key, generator) in block_missing for key in block_missing for generator in GENERATORS)
    block_missing_family = collections.Counter(
        block["family"] for block, image in zip(blocks, block_duals) if image not in block_set)
    block_missing_orbits = orbit_histogram(block_missing, tblock) if block_missing else {}

    selectors = source["selectors"]
    selector_keys = [selector_key(selector) for selector in selectors]
    selector_set = set(selector_keys)
    assert len(selector_keys) == len(selector_set)
    selector_hashes = set()
    for selector, key in zip(selectors, selector_keys):
        semantic = selector_semantics(key)
        digest = canonical_sha(semantic)
        assert selector["selector_semantic_sha256"] == digest
        assert selector["selected_names"] == semantic["selected_names"]
        assert digest not in selector_hashes
        selector_hashes.add(digest)
    selector_duals = [dselector(key) for key in selector_keys]
    assert len(set(selector_duals)) == len(selector_duals)
    assert all(dselector(dkey) == key for key, dkey in zip(selector_keys, selector_duals))
    selector_missing = set(selector_duals) - selector_set
    selector_intersection = len(selector_set) - len(selector_missing)
    assert all(tselector(key, generator) in selector_missing
               for key in selector_missing for generator in GENERATORS)
    selector_missing_sector = collections.Counter(key[0] for key in selector_missing)
    selector_missing_orbits = orbit_histogram(selector_missing, tselector) if selector_missing else {}
    selector_existing_orbits = orbit_histogram(selector_set, tselector)

    result = {
        "schema": "circdist-gross-round124-iter198-css-duality-registry-audit-v1",
        "status": "PASS",
        "bindings": {
            "source_sha256": file_sha(args.source),
            "source_semantic_payload_sha256": claimed_semantic,
            "state_sha256": file_sha(args.state),
            "candidate_sha256": file_sha(args.candidate),
            "candidate_schedule_sha256": candidate["compressed_schedule_sha256"],
        },
        "action": {
            "name": "CSS duality D extending Z_12 x Z_6",
            "check": "g -> -g",
            "qubit": "q<72 -> 72+(-q); q=72+r -> -r",
            "edge": "X:c:q <-> Z:-c:D(q)",
            "selector": "Xerr <-> Zerr; D:q -> D:D(q); R:c:k -> R:-c:k",
            "residual_kind_action": "identity on k in {0,1,2}; order positions and layer labels unchanged",
            "relations": ["D^2=1", "D T_delta D=T_-delta"],
            "translation_subgroup_order": 72,
            "extended_group_order": 144,
            "distinct_concrete_edge_permutations": len(action_hashes),
            "involution_edge_cases": involution_edge_cases,
            "translation_composition_edge_cases": translation_composition_cases,
            "conjugation_edge_cases": conjugation_edge_cases,
        },
        "geometry": {
            "status": "PASS", "named_edges": len(edges),
            "check_image_cases": geometry_check_cases, "mc_overlap_image_cases": len(overlap_set),
            "sector_swap": "X hook/Z detector/stabilizer quotient maps exactly to Z hook/X detector/stabilizer quotient and conversely",
            "stabilizer_rank_each": 66, "detector_rank_each": 66,
            "detector_plus_logical_rank_each": 78,
            "kernel_dimension": 66,
            "logical_criterion": "within zero syndrome, all 12 logical parities vanish iff the support is in the sector stabilizer span",
        },
        "schedule_transport": {"original": schedule_original, "dual": schedule_dual,
                               "layer_multiset_preserved": True},
        "blocks": {
            "input_count": len(block_set), "dual_image_count": len(set(block_duals)),
            "already_dual_paired_count": block_intersection,
            "missing_dual_image_count": len(block_missing),
            "closed_union_count": len(block_set | set(block_duals)),
            "missing_by_parent_family": dict(sorted(block_missing_family.items())),
            "missing_translation_orbit_histogram": block_missing_orbits,
            "missing_set_generator_cases": len(block_missing) * len(GENERATORS),
            "identity_rule": "full sorted ordered-atom tuple",
        },
        "selectors": {
            "input_count": len(selector_set), "dual_image_count": len(set(selector_duals)),
            "already_dual_paired_count": selector_intersection,
            "missing_dual_image_count": len(selector_missing),
            "closed_union_count": len(selector_set | set(selector_duals)),
            "missing_by_target_sector": dict(sorted(selector_missing_sector.items())),
            "existing_translation_orbit_histogram": selector_existing_orbits,
            "missing_translation_orbit_histogram": selector_missing_orbits,
            "missing_set_generator_cases": len(selector_missing) * len(GENERATORS),
            "identity_rule": "full (sector,sorted data,sorted (check,sorted kinds)) tuple",
        },
        "soundness_lemma": (
            "D is a bijection of the frozen physical schedule space preserving resource conflicts, "
            "the equality of the two MC orientations, global interleaving, and layer labels.  It swaps "
            "the two CSS error sectors, maps residual order position k identically, maps zero syndrome "
            "to zero syndrome, and maps stabilizer span to stabilizer span.  Therefore the D-image of "
            "every reviewed order exclusion and exact selector exclusion is sound; translation closure "
            "of the missing image sets follows from D T_delta D=T_-delta."
        ),
        "information_gain": (
            "The iteration-198 registry is claimed closed under translations and the CSS involution.  The missing counts here are the exact opposite "
            "CSS coset exclusions added by D; the union supports all 144 generalized-dihedral images."
        ),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({
        "status": "PASS", "blocks": len(block_set),
        "missing_dual_blocks": len(block_missing), "closed_blocks": len(block_set | set(block_duals)),
        "selectors": len(selector_set), "missing_dual_selectors": len(selector_missing),
        "closed_selectors": len(selector_set | set(selector_duals)),
        "selector_missing_orbits": selector_missing_orbits,
    }, sort_keys=True))


if __name__ == "__main__":
    main()
